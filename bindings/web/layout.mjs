// Writes src/layout.ts, the C struct offsets the binding reads, from tests/support/layout.c built
// to wasm32. With --check it only compares, which the web.layout test runs so a struct change
// cannot reach the binding unnoticed.   node layout.mjs <rant_web_layout.cjs> [--check]

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const [program, flag] = process.argv.slice(2);
const target = fileURLToPath(new URL("./src/layout.ts", import.meta.url));

const structs = new Map();
for (const line of execFileSync(process.execPath, [program], { encoding: "utf8" }).split(/\r?\n/)) {
    const [name, value] = line.trim().split(" ");
    if (!name) continue;
    /* a union member reads v.u, and sizeof is a key no C field can take */
    const [struct, ...path] = name.split(".");
    if (!structs.has(struct)) structs.set(struct, []);
    structs.get(struct).push([path.length ? path.join("_") : "sizeof", Number(value)]);
}

let text = "/* Generated by layout.mjs from tests/support/layout.c built to wasm32. Never edit it: build the\n" +
           " * web_layout target after a public struct changes. */\n";
for (const [struct, fields] of structs)
    text += `\nexport const ${struct} = { ${fields.map(([f, v]) => `${f}: ${v}`).join(", ")} } as const;\n`;

if (flag === "--check") {
    let now = "";
    try { now = readFileSync(target, "utf8").replace(/\r\n/g, "\n"); } catch { /* none yet */ }
    if (now !== text) {
        console.error("src/layout.ts does not match the C structs: build the web_layout target and commit it");
        process.exit(1);
    }
    console.log("ok   src/layout.ts matches the C structs");
} else {
    writeFileSync(target, text);
    console.log(`wrote ${target}`);
}
