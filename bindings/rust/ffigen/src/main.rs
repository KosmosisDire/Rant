//! Regenerates `rant/src/ffi.rs` from `dist/rant.h`. With `--check` it changes nothing and
//! exits 1 when the checked in file is stale, or 77 (a ctest skip) when libclang is missing.

use std::path::{Path, PathBuf};
use std::process::ExitCode;

include!("../../rant/dist.rs");

const SKIPPED: u8 = 77;

fn main() -> ExitCode {
    let check = std::env::args().any(|a| a == "--check");
    let here = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let crate_dir = here.parent().expect("ffigen sits in the workspace").join("rant");
    let target = crate_dir.join("src/ffi.rs");
    let header = match amalgamate(&crate_dir, &std::env::temp_dir().join("rant-ffigen")) {
        Ok(dir) => dir.join("rant.h"),
        Err(e) => {
            eprintln!("ffigen: {e}");
            return ExitCode::FAILURE;
        }
    };
    // bindgen panics when it cannot load libclang, the one failure that skips
    let generated = match std::panic::catch_unwind(|| generate(&header, &here.join("include"))) {
        Ok(Ok(text)) => text,
        Ok(Err(e)) => {
            eprintln!("ffigen: bindgen failed on {}: {e}", header.display());
            return ExitCode::FAILURE;
        }
        Err(panic) => {
            let text = panic.downcast_ref::<String>().map(String::as_str)
                .or_else(|| panic.downcast_ref::<&str>().copied()).unwrap_or("");
            if !text.contains("libclang") {
                std::panic::resume_unwind(panic);
            }
            eprintln!("ffigen: SKIPPED, libclang could not be loaded (set LIBCLANG_PATH)");
            return ExitCode::from(SKIPPED);
        }
    };
    // a Windows checkout may hand ffi.rs back with CRLF line ends
    let current = std::fs::read_to_string(&target).unwrap_or_default().replace("\r\n", "\n");
    if check {
        if current == generated {
            println!("ffigen: ffi.rs matches {}", header.display());
            return ExitCode::SUCCESS;
        }
        eprintln!("ffigen: ffi.rs is stale, run `cargo run -p rant-ffigen` in bindings/rust");
        return ExitCode::FAILURE;
    }
    if current != generated {
        std::fs::write(&target, generated).expect("ffigen: cannot write ffi.rs");
        println!("ffigen: wrote {}", target.display());
    } else {
        println!("ffigen: ffi.rs is current");
    }
    ExitCode::SUCCESS
}

fn generate(header: &Path, stubs: &Path) -> Result<String, bindgen::BindgenError> {
    let target = bindgen::RustTarget::stable(85, 0).expect("ffigen: Rust 1.85 is a known target");
    let bindings = bindgen::Builder::default()
        .header(header.to_string_lossy())
        // One canonical target, so every host writes the same file. The public API has no
        // long, so the result is right for every 64 and 32 bit target.
        .clang_arg("--target=x86_64-unknown-linux-gnu")
        .clang_arg("-ffreestanding")
        .clang_arg("-std=c99")
        .clang_arg(format!("-isystem{}", stubs.display()))
        .allowlist_function("rant_.*")
        .allowlist_type("Rant.*")
        .allowlist_var("RANT_.*")
        // the binding reads rant_version() at run time, so a version bump leaves ffi.rs alone
        .blocklist_item("RANT_VERSION")
        .default_enum_style(bindgen::EnumVariation::Consts)
        .prepend_enum_name(false)
        .layout_tests(false)
        .derive_default(true)
        .derive_debug(false)
        .generate_comments(false)
        .merge_extern_blocks(true)
        .rust_target(target)
        .rust_edition(bindgen::RustEdition::Edition2024)
        .formatter(bindgen::Formatter::Prettyplease)
        .raw_line("// Generated by ffigen from dist/rant.h. Run `cargo run -p rant-ffigen` after a header change.")
        .generate()?;
    // bindgen writes CRLF around its header lines on Windows
    Ok(bindings.to_string().replace("\r\n", "\n"))
}
