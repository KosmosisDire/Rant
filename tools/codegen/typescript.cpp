// The TypeScript backend: the value types of the web binding and its table of schemas. A value is a
// plain object matched by shape and a schema is its name, so no package or reflection is needed.
#include "backends.hpp"

#include <map>
#include <stdexcept>

namespace codegen {

static std::string js_doc(const std::string &text, const std::string &indent) {
    if (text.empty()) return "";
    std::string body;
    for (size_t i = 0; i < text.size(); i++) {
        if (text[i] == '*' && i + 1 < text.size() && text[i + 1] == '/') body += "* ";
        else if (text[i] == '\n') body += "\n" + indent + " * ";
        else body += text[i];
    }
    return indent + "/** " + body + " */\n";
}

static std::string about_text(const Def &d) {
    std::string joined;
    for (size_t i = 0; i < d.about.size(); i++) joined += (i ? "\n" : "") + d.about[i];
    return joined;
}

using Defs = std::map<std::string, const Def *>;

// A variable or fixed array of numbers decodes to its typed array, one copy out of the message.
static std::string typed_array(const std::string &word) {
    static const std::map<std::string, std::string> arrays = {
        { "u8", "Uint8Array" }, { "u16", "Uint16Array" }, { "u32", "Uint32Array" }, { "u64", "BigUint64Array" },
        { "i8", "Int8Array" }, { "i16", "Int16Array" }, { "i32", "Int32Array" }, { "i64", "BigInt64Array" },
        { "f32", "Float32Array" }, { "f64", "Float64Array" } };
    const auto it = arrays.find(word);
    return it == arrays.end() ? "" : it->second;
}

static std::string value_of(const Type &t, const Defs &defs) {
    switch (t.kind) {
    case Type::Scalar:
        if (t.word == "bool") return "boolean";
        return t.word == "u64" || t.word == "i64" ? "bigint" : "number";
    case Type::String: return "string";
    case Type::Named: return defs.at(t.word)->kind == Def::Enum ? t.word : t.word + "Value";
    case Type::Array: {
        if (t.elem->kind == Type::Scalar && !typed_array(t.elem->word).empty()) return typed_array(t.elem->word);
        return value_of(*t.elem, defs) + "[]";
    }
    case Type::Map: break;
    }
    throw std::runtime_error("the TypeScript types hold no map");
}

// The value type's name: an enum is its options, anything else has Value after it.
static std::string value_name(const Def &d) { return d.kind == Def::Enum ? d.name : d.name + "Value"; }

static std::string ts_def(const Def &d, const Defs &defs) {
    std::string out = js_doc(about_text(d), "");
    if (d.kind == Def::Enum) {
        out += "export type " + d.name + " =";
        for (size_t i = 0; i < d.members.size(); i++) out += (i ? " | \"" : " \"") + d.members[i].name + "\"";
        return out + ";\n";
    }
    if (d.kind == Def::Alias) return out + "export type " + value_name(d) + " = " + value_of(d.members[0].type, defs) + ";\n";
    if (d.members.empty()) return out + "export type " + value_name(d) + " = Record<string, never>;\n";
    out += "export interface " + value_name(d) + " {\n";
    for (const Member &m : d.members)
        out += js_doc(comment_of(m), "    ") + "    " + m.name + ": " + value_of(m.type, defs) + ";\n";
    return out + "}\n";
}

static std::string types_source(const Model &model) {
    std::string out = "/* Generated by rant_codegen from types/stdtypes.schema, do not edit. */\n";
    out += "/* The standard types: the value of each, and its schema by name in `types`. */\n\n";
    out += "import { named } from \"./schema.js\";\n\n";
    Defs defs;
    for (const Def &d : model.defs) {
        defs[d.name] = &d;
        out += ts_def(d, defs) + "\n";
    }
    out += "/** The standard types of docs/stdtypes.md, by name. */\nexport const types = {\n";
    for (const Def &d : model.defs) out += "    " + d.name + ": named<" + value_name(d) + ">(\"" + d.name + "\"),\n";
    return out + "} as const;\n";
}

std::vector<Output> write_typescript(const Model &model) {
    return { { "bindings/web/src/stdtypes.ts", types_source(model) } };
}

}  // namespace codegen
