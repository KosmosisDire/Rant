// The C# backend: the structs and enums of the Rant.Types assembly. The middleware reflects over
// them at run time, so nothing else is generated for it.
#include "backends.hpp"

#include <cctype>
#include <map>
#include <stdexcept>

namespace codegen {

static std::string xml(const std::string &text) {
    std::string out;
    for (char c : text) {
        if (c == '&') out += "&amp;";
        else if (c == '<') out += "&lt;";
        else if (c == '>') out += "&gt;";
        else out += c;
    }
    return out;
}

static std::string summary(const std::string &text, const std::string &indent) {
    if (text.empty()) return "";
    std::string out = indent + "/// <summary>";
    for (char c : xml(text)) {
        if (c == '\n') out += "\n" + indent + "/// ";
        else out += c;
    }
    return out + "</summary>\n";
}

static std::string about_text(const Def &d) {
    std::string joined;
    for (size_t i = 0; i < d.about.size(); i++) joined += (i ? "\n" : "") + d.about[i];
    return joined;
}

// field_of_view to FieldOfView, which the library's name rule reads back as the wire name.
static std::string pascal(const std::string &wire) {
    std::string out;
    bool start = true;
    for (char c : wire) {
        if (c == '_') { start = true; continue; }
        out += start ? (char)toupper((unsigned char)c) : c;
        start = false;
    }
    if (snake(out) != wire) throw std::runtime_error(wire + " does not read back from " + out);
    return out;
}

static std::string cs_scalar(const std::string &word) {
    static const std::map<std::string, std::string> types = {
        { "u8", "byte" }, { "u16", "ushort" }, { "u32", "uint" }, { "u64", "ulong" },
        { "i8", "sbyte" }, { "i16", "short" }, { "i32", "int" }, { "i64", "long" },
        { "f32", "float" }, { "f64", "double" }, { "bool", "bool" } };
    return types.at(word);
}

using Defs = std::map<std::string, const Def *>;

struct Spelled {
    std::string attrs, type;
};

// A member's attributes and type. An alias is no C# type: the member holds what it holds and
// RantTypeName names it, so the wire spells the standard name.
static Spelled cs_member(const Type &t, const Defs &defs) {
    switch (t.kind) {
    case Type::Scalar: return { "", cs_scalar(t.word) };
    case Type::String:
        return { t.cap ? "[RantString(" + std::to_string(t.cap) + ")] " : "", "string" };
    case Type::Named: {
        const Def &d = *defs.at(t.word);
        if (d.kind != Def::Alias) return { "", d.name };
        Spelled inner = cs_member(d.members[0].type, defs);
        inner.attrs = "[RantTypeName(\"" + d.name + "\")] " + inner.attrs;
        return inner;
    }
    case Type::Array: {
        std::string counts, levels;
        bool any = false;
        const Type *e = &t;
        for (; e->kind == Type::Array; e = e->elem.get()) {
            counts += (levels.empty() ? "" : ", ") + std::to_string(e->count);
            levels += "[]";
            any = any || e->count;
        }
        if (e->kind == Type::Named && defs.at(e->word)->kind == Def::Alias)
            throw std::runtime_error("the C# types hold no array of an alias, " + e->word);
        const Spelled elem = cs_member(*e, defs);
        return { (any ? "[RantArray(" + counts + ")] " : "") + elem.attrs, elem.type + levels };
    }
    case Type::Map: break;
    }
    throw std::runtime_error("the C# types hold no map");
}

static std::string cs_def(const Def &d, const Defs &defs) {
    const std::string in = "        ";
    std::string out = summary(about_text(d), "    ");
    if (d.kind == Def::Enum) {
        out += "    [RantSchema(\"" + d.name + "\")] public enum " + d.name + " : " + cs_scalar(d.backing) + "\n    {\n";
        for (size_t i = 0; i < d.members.size(); i++) {
            const Member &m = d.members[i];
            out += summary(comment_of(m), in) + in + m.name + " = " + std::to_string(m.value) +
                   (i + 1 < d.members.size() ? "," : "") + "\n";
        }
        return out + "    }\n";
    }
    if (d.members.empty()) return out + "    [RantSchema(\"" + d.name + "\")] public struct " + d.name + " { }\n";
    out += "    [RantSchema(\"" + d.name + "\")] public struct " + d.name + "\n    {\n";
    for (const Member &m : d.members) {
        const Spelled s = cs_member(m.type, defs);
        out += summary(comment_of(m), in) + in + s.attrs + "public " + s.type + " " + pascal(m.name) + ";\n";
    }
    return out + "    }\n";
}

static std::string types_source(const Model &model, const std::string &extras) {
    Defs defs;
    std::string out = "// Generated by rant_codegen from types/stdtypes.schema and types/extras.cs, do not edit.\n";
    out += "// The standard types as C# structs. A member with no words of its own needs none.\n";
    out += "#pragma warning disable CS1591\n\n";
    out += extras + "\n";
    out += "// Apart from the root so a mirror such as Color or Quaternion never clashes with an engine type\n"
           "// of the same name. Each compiles against the standard definition of its name.\n";
    out += "namespace Rant.Types\n{\n";
    for (size_t i = 0; i < model.defs.size(); i++) {
        const Def &d = model.defs[i];
        defs[d.name] = &d;
        if (d.kind == Def::Alias) continue;
        out += cs_def(d, defs);
        out += i + 1 < model.defs.size() ? "\n" : "";
    }
    return out + "}\n";
}

std::vector<Output> write_csharp(const Model &model, const std::string &extras) {
    return { { "bindings/csharp/types/Types.cs", types_source(model, extras) } };
}

}  // namespace codegen
